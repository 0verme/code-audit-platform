RULES_BY_ID = MappingProxyType({rule.id: rule for rule in RULES})


def resolve_rule(rule_id: str) -> RuleDefinition | None:
    """Return static metadata for a registered business rule ID."""
    return RULES_BY_ID.get(rule_id)


def rule_inventory() -> tuple[dict[str, object], ...]:
    """Return a machine-readable inventory using the short ``severity`` key."""
    inventory = []
    for rule in RULES:
        entry = asdict(rule)
        entry["severity"] = entry.pop("default_severity")
        inventory.append(entry)
    return tuple(inventory)
