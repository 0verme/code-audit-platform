"""Static, typed metadata for business audit rules.

This registry describes existing checks only. It neither configures policies nor
executes a checker; policy values remain in audit_rules.yaml and behavior stays
in the workflow implementation.
"""
from __future__ import annotations

from dataclasses import asdict, dataclass
from types import MappingProxyType
from typing import Literal


Workflow = Literal["hcyt", "nups", "fine-report"]
Category = Literal[
    "sql", "ddl", "python", "script", "schedule", "dependency",
    "metadata", "asset_registry", "config", "menu", "permission", "report",
]
Severity = Literal["err", "warn"]


@dataclass(frozen=True, slots=True)
class RuleImplementation:
    module: str
    function: str


@dataclass(frozen=True, slots=True)
class RuleDefinition:
    id: str
    workflow: Workflow
    category: Category
    title: str
    default_severity: Severity
    description: str
    rationale: str
    trigger_condition: str
    artifact: str
    config_keys: tuple[str, ...]
    implementation: tuple[RuleImplementation, ...]


def _rule(
    rule_id: str,
    workflow: Workflow,
    category: Category,
    title: str,
    severity: Severity,
    description: str,
    rationale: str,
    trigger: str,
    artifact: str,
    module: str,
    function: str,
    config: tuple[str, ...] = (),
    additional_implementations: tuple[RuleImplementation, ...] = (),
) -> RuleDefinition:
    return RuleDefinition(
        id=rule_id,
        workflow=workflow,
        category=category,
        title=title,
        default_severity=severity,
        description=description,
        rationale=rationale,
        trigger_condition=trigger,
        artifact=artifact,
        config_keys=config,
        implementation=(RuleImplementation(module, function), *additional_implementations),
    )


